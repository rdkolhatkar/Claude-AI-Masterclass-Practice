def greet(name):
    return "Hello, " + name


def add(a, b):
    return a + b


def multiply(a, b):
    """Return the product of two numbers.

    Args:
        a: The first number.
        b: The second number.

    Returns:
        The product of a and b.
    """
    return a * b






print(greet("World"))
print(add(2, 3))

